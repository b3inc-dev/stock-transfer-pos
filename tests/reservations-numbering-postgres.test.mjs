import assert from "node:assert/strict";
import { test } from "node:test";
import process from "node:process";
import { readFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
const run = promisify(execFile);
const url = process.env.RESERVATION_TEST_DATABASE_URL;
test("Postgres backfill and concurrent numbering preserve replay keys, shop isolation and settings", { skip: !url }, async () => {
  const parsed = new URL(url);
  assert.equal(parsed.hostname, "127.0.0.1"); assert.equal(parsed.pathname, "/reservation_fixture");
  const sql = async input => (await run("psql", [url, "-X", "-At", "-v", "ON_ERROR_STOP=1", "-c", input])).stdout.trim();
  for (const migration of ["20261125000000_stock_reservations", "20261125010000_reservation_receipt_layout"]) await sql(await readFile(`prisma/migrations/${migration}/migration.sql`, "utf8"));
  const insert = (id, shop = "a.myshopify.com", at = "2026-11-25") => `INSERT INTO "StockReservation" ("id","shop","locationId","locationName","timezone","status","lines","dueDate","createdBy","updatedAt","createdAt") VALUES ('${id}','${shop}','L1','Test','Asia/Tokyo','held','[]','2026-12-02','test',NOW(),'${at}')`;
  await sql(insert("legacy-late", undefined, "2026-11-24") + ";" + insert("legacy-first", undefined, "2026-11-23") + ";" + insert("legacy-b", "b.myshopify.com"));
  await sql(`INSERT INTO "StockReservationSettings" ("shop","days","receiptLayout","receiptVersion","updatedAt") VALUES ('a.myshopify.com',14,'{"keep":"value"}',9,NOW())`);
  await sql(await readFile("prisma/migrations/20261125020000_reservation_display_numbers/migration.sql", "utf8"));
  assert.equal(await sql(`SELECT "id"||':'||"number" FROM "StockReservation" ORDER BY "id"`), "legacy-b:1\nlegacy-first:1\nlegacy-late:2");
  assert.equal(await sql(`SELECT "days"||':'||"receiptVersion"||':'||("receiptLayout"->>'keep') FROM "StockReservationSettings" WHERE "shop"='a.myshopify.com'`), "14:9:value");
  assert.equal(await sql(`SELECT COUNT(*) FROM "StockReservation" WHERE "intakeMethod" IS NOT NULL`), "0");
  const assigned = await Promise.all(Array.from({ length: 40 }, (_, index) => sql(insert(`concurrent-${index}`) + ' RETURNING "number"')));
  const numbers = assigned.map(output => Number(output.split("\n")[0])).sort((a,b) => a-b);
  assert.deepEqual(numbers, Array.from({length:40},(_,index)=>index+3));
  const nextBeforeReplay = await sql(`SELECT "nextReservationNumber" FROM "StockReservationSettings" WHERE "shop"='a.myshopify.com'`);
  await assert.rejects(sql(insert("legacy-first")), /duplicate key/);
  assert.equal(await sql(`SELECT "nextReservationNumber" FROM "StockReservationSettings" WHERE "shop"='a.myshopify.com'`), nextBeforeReplay);
  assert.equal((await sql(insert("second-b", "b.myshopify.com")+' RETURNING "number"')).split("\n")[0], "2");
  assert.equal((await sql(insert("new-shop", "c.myshopify.com")+' RETURNING "number"')).split("\n")[0], "1");
  assert.equal(await sql(`SELECT COUNT(*) FROM "StockReservation" WHERE "id"='legacy-first' AND "number"=1`), "1");
});
